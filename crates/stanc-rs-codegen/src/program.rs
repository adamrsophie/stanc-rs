//! The generated module: user functions, the model struct, its constructor, and the
//! `GeneratedModel` implementation.

use stanc_rs_semantic::typed::{TExpr, TProgram, TSizedType, TStmt, TStmtKind, TTransformation};
use stanc_rs_semantic::types::Ad;
use stanc_rs_syntax::ast::{FnSuffix, UnsizedType as U};

use crate::expr::rust_type;
use crate::{Gen, R, UdfDef, mangle, unsupported};

/// A top-level variable declaration.
#[derive(Clone)]
struct Decl {
    name: String,
    ty: TSizedType,
    trans: TTransformation,
}

fn decls(block: &[TStmt]) -> Vec<Decl> {
    let mut out = Vec::new();
    for s in block {
        if let TStmtKind::VarDecl {
            ty, trans, vars, ..
        } = &s.kind
        {
            for v in vars {
                out.push(Decl {
                    name: v.name.clone(),
                    ty: ty.clone(),
                    trans: trans.clone(),
                });
            }
        }
    }
    out
}

/// The innermost (non-array) part of a sized type and its array sizes.
fn parts(ty: &TSizedType) -> (Vec<&TExpr>, &TSizedType) {
    ty.array_parts()
}

impl Gen {
    pub(crate) fn program(&mut self, p: &TProgram) -> R<()> {
        self.line(&format!(
            "// Generated by stanc-rs from the Stan program `{}`. Do not edit.",
            p.name
        ));
        self.line("");
        self.line("#[allow(unused_imports)]");
        self.line("use stanc_rs_runtime as rt;");
        self.line("#[allow(unused_imports)]");
        self.line("use rt::stanmath_rs::prelude as sm;");
        self.line("#[allow(unused_imports)]");
        self.line("use sm::Real as _;");
        self.line("");
        self.functions(&p.functions)?;

        let data = decls(&p.data);
        let tdata = decls(&p.transformed_data);
        let params = decls(&p.parameters);
        let tparams = decls(&p.transformed_parameters);
        let gq = decls(&p.generated_quantities);

        // The struct.
        self.line("/// The compiled Stan model.");
        self.line("#[allow(non_snake_case, dead_code)]");
        self.line("pub struct Model {");
        self.indent += 1;
        for d in data.iter().chain(&tdata) {
            let t = rust_type(&d.ty.unsized_type(), &Ad::DataOnly);
            self.line(&format!("pub {}: {t},", mangle(&d.name)));
        }
        self.line("info__: Vec<rt::VarInfo>,");
        self.line("num_unconstrained__: usize,");
        self.indent -= 1;
        self.line("}");
        self.line("");

        // The constructor.
        self.line(LINT_ALLOW);
        self.line("impl Model {");
        self.indent += 1;
        self.line("/// Reads the data, runs the transformed data block, and checks every declared constraint.");
        self.line("pub fn new(data__: &rt::data::Data, seed__: u64) -> rt::Result<Model> {");
        self.indent += 1;
        self.line("let build__ = || -> rt::Result<Model> {");
        self.indent += 1;
        self.line("type T = f64;");
        self.line("let mut rng_state__ = <rt::rand::rngs::StdRng as rt::rand::SeedableRng>::seed_from_u64(seed__);");
        self.line("let rng__: &mut dyn rt::rand::Rng = &mut rng_state__;");
        self.line("let jacobian__ = false;");
        self.line("let propto__ = false;");
        self.line("let mut target_val__ = 0.0_f64;");
        self.line("let target__ = &mut target_val__;");
        self.fields.clear();
        for d in &data {
            let uty = d.ty.unsized_type();
            let src = if matches!(uty, U::Int | U::Real | U::Complex | U::Tuple(_)) {
                format!("data__.get({:?})?", d.name)
            } else {
                format!("data__.get_or_empty({:?})", d.name)
            };
            let read = self.read_json(&d.ty, &d.name, &src)?;
            self.line(&format!(
                "let {}: {} = {read};",
                mangle(&d.name),
                rust_type(&uty, &Ad::DataOnly)
            ));
            self.check_decl(d, &Ad::DataOnly)?;
        }
        self.stmts(&p.transformed_data)?;
        for d in &tdata {
            self.check_decl(d, &Ad::DataOnly)?;
        }
        // Shapes of the output variables and the number of unconstrained parameters.
        self.line("let info__ = vec![");
        self.indent += 1;
        for (block, ds) in [
            ("Parameters", &params),
            ("TransformedParameters", &tparams),
            ("GeneratedQuantities", &gq),
        ] {
            for d in ds {
                let info = self.var_info(d, block)?;
                self.line(&format!("{info},"));
            }
        }
        self.indent -= 1;
        self.line("];");
        let mut unc = vec!["0_usize".to_string()];
        for d in &params {
            unc.push(self.unconstrained_size(d)?);
        }
        self.line(&format!(
            "let num_unconstrained__: usize = {};",
            unc.join(" + ")
        ));
        let names: Vec<String> = data.iter().chain(&tdata).map(|d| mangle(&d.name)).collect();
        let fields = if names.is_empty() {
            String::new()
        } else {
            format!("{}, ", names.join(", "))
        };
        self.line(&format!(
            "Ok(Model {{ {fields}info__, num_unconstrained__ }})"
        ));
        self.indent -= 1;
        self.line("};");
        self.line("build__().map_err(rt::ModelError::in_data)");
        self.indent -= 1;
        self.line("}");
        self.indent -= 1;
        self.line("}");
        self.line("");

        self.fields = data.iter().chain(&tdata).map(|d| d.name.clone()).collect();
        self.line(LINT_ALLOW);
        self.line("impl rt::GeneratedModel for Model {");
        self.indent += 1;
        self.line(&format!(
            "fn model_name(&self) -> &'static str {{ {:?} }}",
            p.name
        ));
        self.line("fn num_unconstrained(&self) -> usize { self.num_unconstrained__ }");
        self.line("fn var_info(&self) -> Vec<rt::VarInfo> { self.info__.clone() }");
        self.line("");

        // Log density.
        self.line("fn log_prob_generic<T: rt::check::Scalar>(&self, theta__: &[T], jacobian__: bool, propto__: bool) -> rt::Result<T> {");
        self.indent += 1;
        self.line("let mut target_val__ = T::from_f64(0.0);");
        self.line("let target__ = &mut target_val__;");
        self.line("let mut in__ = rt::io::Reader::new(theta__);");
        for d in &params {
            self.read_param(d)?;
        }
        self.stmts(&p.transformed_parameters)?;
        for d in &tparams {
            self.check_decl(d, &Ad::AutoDiffable)?;
        }
        self.line("{");
        self.indent += 1;
        self.stmts(&p.model)?;
        self.indent -= 1;
        self.line("}");
        self.line("Ok(target_val__)");
        self.indent -= 1;
        self.line("}");
        self.line("");

        // Constrained values.
        self.line("fn write_array_impl(&self, theta__: &[f64], include_tp__: bool, include_gq__: bool, rng__: &mut dyn rt::rand::Rng) -> rt::Result<Vec<f64>> {");
        self.indent += 1;
        self.line("type T = f64;");
        self.line("let jacobian__ = false;");
        self.line("let propto__ = false;");
        self.line("let mut target_val__ = 0.0_f64;");
        self.line("let target__ = &mut target_val__;");
        self.line("let mut in__ = rt::io::Reader::new(theta__);");
        self.line("let mut out__: Vec<f64> = Vec::new();");
        let mut k = 0;
        for d in &params {
            self.read_param(d)?;
        }
        for d in &params {
            self.line(&format!(
                "rt::names::push_output(&mut out__, &{}, &self.info__[{k}]);",
                mangle(&d.name)
            ));
            k += 1;
        }
        self.line("if !(include_tp__ || include_gq__) { return Ok(out__); }");
        self.stmts(&p.transformed_parameters)?;
        for d in &tparams {
            self.check_decl(d, &Ad::DataOnly)?;
        }
        self.line("if include_tp__ {");
        self.indent += 1;
        for d in &tparams {
            self.line(&format!(
                "rt::names::push_output(&mut out__, &{}, &self.info__[{k}]);",
                mangle(&d.name)
            ));
            k += 1;
        }
        self.indent -= 1;
        self.line("}");
        self.line("if !include_gq__ { return Ok(out__); }");
        self.stmts(&p.generated_quantities)?;
        for d in &gq {
            self.check_decl(d, &Ad::DataOnly)?;
        }
        for d in &gq {
            self.line(&format!(
                "rt::names::push_output(&mut out__, &{}, &self.info__[{k}]);",
                mangle(&d.name)
            ));
            k += 1;
        }
        self.line("Ok(out__)");
        self.indent -= 1;
        self.line("}");
        self.line("");

        // Unconstraining.
        self.line(
            "fn unconstrain_json(&self, values__: &rt::data::Data) -> rt::Result<Vec<f64>> {",
        );
        self.indent += 1;
        self.line("type T = f64;");
        self.line("let mut w__: Vec<f64> = Vec::new();");
        for d in &params {
            self.free_param(d)?;
        }
        self.line("Ok(w__)");
        self.indent -= 1;
        self.line("}");
        self.indent -= 1;
        self.line("}");
        Ok(())
    }

    fn functions(&mut self, fs: &[TStmt]) -> R<()> {
        // Register every signature first (overloads get numbered Rust names).
        for f in fs {
            if let TStmtKind::FunDef {
                ret, name, args, ..
            } = &f.kind
            {
                let defs = self.udfs.entry(name.clone()).or_default();
                if defs
                    .iter()
                    .any(|d| d.args.iter().map(|a| &a.ty).eq(args.iter().map(|a| &a.ty)))
                {
                    continue;
                }
                let k = defs.len();
                let rust_name = if k == 0 {
                    format!("uf_{name}")
                } else {
                    format!("uf_{name}_{k}")
                };
                defs.push(UdfDef {
                    rust_name,
                    args: args.clone(),
                    ret: ret.clone(),
                });
            }
        }
        for f in fs {
            let TStmtKind::FunDef {
                ret,
                name,
                args,
                body,
            } = &f.kind
            else {
                continue;
            };
            let Some(body) = body else { continue };
            let def = self.udfs[name]
                .iter()
                .find(|d| d.args.iter().map(|a| &a.ty).eq(args.iter().map(|a| &a.ty)))
                .cloned()
                .expect("registered");
            let suffix = FnSuffix::from_name(name);
            let mut params = Vec::new();
            for a in args {
                if matches!(a.ty, U::Function(_)) {
                    return Err(unsupported(
                        f.span,
                        "function-typed arguments are not supported by stanc-rs yet",
                    ));
                }
                let ad: Ad = Ad::from(a.ad).fill_for(&a.ty);
                params.push(format!("{}: {}", mangle(&a.name), rust_type(&a.ty, &ad)));
            }
            match suffix {
                FnSuffix::Rng => params.push("rng__: &mut dyn rt::rand::Rng".into()),
                FnSuffix::Lp => params.push("target__: &mut T".into()),
                FnSuffix::Jacobian => {
                    params.push("target__: &mut T".into());
                    params.push("jacobian__: bool".into());
                }
                FnSuffix::Lpdf | FnSuffix::Lpmf => params.push("propto__: bool".into()),
                FnSuffix::Plain => {}
            }
            let ret_ty = match ret {
                Some(t) => rust_type(t, &Ad::AutoDiffable.fill_for(t)),
                None => "()".into(),
            };
            self.line(LINT_ALLOW);
            self.line(&format!(
                "pub fn {}<T: rt::check::Scalar>({}) -> rt::Result<{ret_ty}> {{",
                def.rust_name,
                params.join(", ")
            ));
            self.indent += 1;
            self.fields.clear();
            self.ret = ret.clone();
            match &body.kind {
                TStmtKind::Block(ss) => self.stmts(ss)?,
                _ => self.stmt(body)?,
            }
            self.ret = None;
            if ret.is_none() {
                self.line("Ok(())");
            } else {
                self.line(&format!(
                    "Err(rt::ModelError::new(rt::ErrorKind::Fatal, {:?}))",
                    format!("function '{name}' ended without returning a value")
                ));
            }
            self.indent -= 1;
            self.line("}");
            self.line("");
        }
        Ok(())
    }

    /// A data reader expression for a value of sized type `ty` from JSON value `src`.
    fn read_json(&mut self, ty: &TSizedType, name: &str, src: &str) -> R<String> {
        let n = format!("{name:?}");
        Ok(match ty {
            TSizedType::Int => format!("rt::data::int({src}, {n})?"),
            TSizedType::Real => format!("rt::data::real({src}, {n})?"),
            TSizedType::Complex => format!("rt::data::complex({src}, {n})?"),
            TSizedType::Vector(k) | TSizedType::RowVector(k) => {
                format!("rt::data::vector({src}, {}, {n})?", self.size(k)?)
            }
            TSizedType::ComplexVector(k) | TSizedType::ComplexRowVector(k) => {
                format!("rt::data::complex_vector({src}, {}, {n})?", self.size(k)?)
            }
            TSizedType::Matrix(r, c) => {
                format!(
                    "rt::data::matrix({src}, {}, {}, {n})?",
                    self.size(r)?,
                    self.size(c)?
                )
            }
            TSizedType::ComplexMatrix(r, c) => {
                format!(
                    "rt::data::complex_matrix({src}, {}, {}, {n})?",
                    self.size(r)?,
                    self.size(c)?
                )
            }
            TSizedType::Array(t, k) => {
                let size = self.size(k)?;
                let v = self.fresh("j");
                let inner = self.read_json(t, name, &v)?;
                format!("rt::data::array({src}, {size}, {n}, |{v}| Ok({inner}))?")
            }
            TSizedType::Tuple(ts) => {
                let mut parts = Vec::new();
                for (i, t) in ts.iter().enumerate() {
                    let slot = format!("rt::data::tuple_slot({src}, {}, {n})?", i + 1);
                    parts.push(self.read_json(t, name, &slot)?);
                }
                format!("({},)", parts.join(", "))
            }
        })
    }

    /// Emits loops over the innermost (non-array) elements of variable `var` with `depth` array
    /// levels; `body` receives a reference expression for each element.
    fn for_leaves(
        &mut self,
        var: &str,
        depth: usize,
        body: &mut dyn FnMut(&mut Gen, &str) -> R<()>,
    ) -> R<()> {
        if depth == 0 {
            let l = self.fresh("leaf");
            self.line(&format!("let {l} = &{var};"));
            return body(self, &l);
        }
        let mut cur = var.to_string();
        for _ in 0..depth {
            let e = self.fresh("e");
            self.line(&format!("for {e} in {cur}.iter() {{"));
            self.indent += 1;
            cur = e;
        }
        body(self, &cur)?;
        for _ in 0..depth {
            self.indent -= 1;
            self.line("}");
        }
        Ok(())
    }

    /// Emits the constraint checks of a declared variable.
    fn check_decl(&mut self, d: &Decl, _ad: &Ad) -> R<()> {
        if matches!(
            d.trans,
            TTransformation::Identity
                | TTransformation::Offset(_)
                | TTransformation::Multiplier(_)
                | TTransformation::OffsetMultiplier(..)
        ) {
            return Ok(());
        }
        let (dims, inner) = parts(&d.ty);
        let var = self.var(&d.name);
        let name = format!("{:?}", d.name);
        let trans = d.trans.clone();
        let inner = inner.clone();
        self.for_leaves(&var, dims.len(), &mut |g, leaf| {
            let vec = || format!("&rt::check::vals({leaf})");
            let mat = || format!("&rt::check::mat_vals({leaf})");
            match &trans {
                TTransformation::Lower(lb) => {
                    let b = g.expr_ref(lb)?;
                    g.line(&format!("rt::check::lower({name}, {leaf}, {b})?;"));
                }
                TTransformation::Upper(ub) => {
                    let b = g.expr_ref(ub)?;
                    g.line(&format!("rt::check::upper({name}, {leaf}, {b})?;"));
                }
                TTransformation::LowerUpper(lb, ub) => {
                    let b = g.expr_ref(lb)?;
                    g.line(&format!("rt::check::lower({name}, {leaf}, {b})?;"));
                    let b = g.expr_ref(ub)?;
                    g.line(&format!("rt::check::upper({name}, {leaf}, {b})?;"));
                }
                TTransformation::Ordered => {
                    g.line(&format!("rt::check::ordered({name}, {})?;", vec()))
                }
                TTransformation::PositiveOrdered => {
                    g.line(&format!("rt::check::positive_ordered({name}, {})?;", vec()))
                }
                TTransformation::Simplex => {
                    g.line(&format!("rt::check::simplex({name}, {})?;", vec()))
                }
                TTransformation::UnitVector => {
                    g.line(&format!("rt::check::unit_vector({name}, {})?;", vec()))
                }
                TTransformation::SumToZero => {
                    if matches!(inner, TSizedType::Matrix(..)) {
                        g.line(&format!(
                            "rt::check::sum_to_zero_matrix({name}, {})?;",
                            mat()
                        ));
                    } else {
                        g.line(&format!("rt::check::sum_to_zero({name}, {})?;", vec()));
                    }
                }
                TTransformation::CholeskyCorr => g.line(&format!(
                    "rt::check::cholesky_factor_corr({name}, {})?;",
                    mat()
                )),
                TTransformation::CholeskyCov => g.line(&format!(
                    "rt::check::cholesky_factor_cov({name}, {})?;",
                    mat()
                )),
                TTransformation::Correlation => {
                    g.line(&format!("rt::check::corr_matrix({name}, {})?;", mat()))
                }
                TTransformation::Covariance => {
                    g.line(&format!("rt::check::cov_matrix({name}, {})?;", mat()))
                }
                TTransformation::StochasticColumn => g.line(&format!(
                    "rt::check::stochastic_column({name}, {})?;",
                    mat()
                )),
                TTransformation::StochasticRow => {
                    g.line(&format!("rt::check::stochastic_row({name}, {})?;", mat()))
                }
                TTransformation::Tuple(_) => {
                    return Err(unsupported(
                        Default::default(),
                        "constraints on tuple components are not supported by stanc-rs yet",
                    ));
                }
                TTransformation::Identity
                | TTransformation::Offset(_)
                | TTransformation::Multiplier(_)
                | TTransformation::OffsetMultiplier(..) => {}
            }
            Ok(())
        })
    }

    /// A bound argument for `rt::io`: a scalar (`Bound::Scalar`) or one value per element.
    fn io_bound(&mut self, e: &TExpr) -> R<String> {
        Ok(match &e.ty {
            U::Int => format!("rt::io::Bound::Scalar(({}) as f64)", self.expr(e)?),
            U::Real => format!("rt::io::Bound::Scalar({})", self.expr(e)?),
            U::Matrix => format!("rt::io::Bound::Each(({}).as_slice())", self.expr_ref(e)?),
            _ => format!("rt::io::Bound::Each({})", self.expr_ref(e)?),
        })
    }

    fn scalar_bound(&mut self, e: &TExpr) -> R<String> {
        Ok(match &e.ty {
            U::Int => format!("(({}) as f64)", self.expr(e)?),
            _ => self.expr(e)?,
        })
    }

    /// The constrained value of one innermost element read from `in__`.
    fn read_inner(&mut self, inner: &TSizedType, trans: &TTransformation) -> R<String> {
        use TTransformation as Tr;
        let lp = "&mut *target__, jacobian__";
        let scalar = |g: &mut Gen, y: &str| -> R<String> {
            Ok(match trans {
                Tr::Identity => y.to_string(),
                Tr::Lower(l) => format!("rt::io::lb({y}, {}, {lp})", g.scalar_bound(l)?),
                Tr::Upper(u) => format!("rt::io::ub({y}, {}, {lp})", g.scalar_bound(u)?),
                Tr::LowerUpper(l, u) => format!(
                    "rt::io::lub({y}, {}, {}, {lp})?",
                    g.scalar_bound(l)?,
                    g.scalar_bound(u)?
                ),
                Tr::Offset(o) => format!(
                    "rt::io::offset_multiplier({y}, {}, 1.0_f64, {lp})?",
                    g.scalar_bound(o)?
                ),
                Tr::Multiplier(m) => format!(
                    "rt::io::offset_multiplier({y}, 0.0_f64, {}, {lp})?",
                    g.scalar_bound(m)?
                ),
                Tr::OffsetMultiplier(o, m) => {
                    format!(
                        "rt::io::offset_multiplier({y}, {}, {}, {lp})?",
                        g.scalar_bound(o)?,
                        g.scalar_bound(m)?
                    )
                }
                _ => {
                    return Err(unsupported(
                        Default::default(),
                        "this constraint on a scalar",
                    ));
                }
            })
        };
        let elementwise = |g: &mut Gen, y: &str| -> R<Option<String>> {
            Ok(Some(match trans {
                Tr::Identity => y.to_string(),
                Tr::Lower(l) => format!("rt::io::lb_each({y}, {}, {lp})?", g.io_bound(l)?),
                Tr::Upper(u) => format!("rt::io::ub_each({y}, {}, {lp})?", g.io_bound(u)?),
                Tr::LowerUpper(l, u) => format!(
                    "rt::io::lub_each({y}, {}, {}, {lp})?",
                    g.io_bound(l)?,
                    g.io_bound(u)?
                ),
                Tr::Offset(o) => {
                    format!(
                        "rt::io::offset_multiplier_each({y}, {}, rt::io::Bound::Scalar(1.0_f64), {lp})?",
                        g.io_bound(o)?
                    )
                }
                Tr::Multiplier(m) => {
                    format!(
                        "rt::io::offset_multiplier_each({y}, rt::io::Bound::Scalar(0.0_f64), {}, {lp})?",
                        g.io_bound(m)?
                    )
                }
                Tr::OffsetMultiplier(o, m) => {
                    format!(
                        "rt::io::offset_multiplier_each({y}, {}, {}, {lp})?",
                        g.io_bound(o)?,
                        g.io_bound(m)?
                    )
                }
                _ => return Ok(None),
            }))
        };
        Ok(match inner {
            TSizedType::Real => scalar(self, "in__.scalar()?")?,
            TSizedType::Vector(n) | TSizedType::RowVector(n) => {
                let n = self.size(n)?;
                match trans {
                    Tr::Ordered => format!("rt::io::ordered(&mut in__, {n}, {lp})?"),
                    Tr::PositiveOrdered => {
                        format!("rt::io::positive_ordered(&mut in__, {n}, {lp})?")
                    }
                    Tr::Simplex => format!("rt::io::simplex(&mut in__, {n}, {lp})?"),
                    Tr::UnitVector => format!("rt::io::unit_vector(&mut in__, {n}, {lp})?"),
                    Tr::SumToZero => format!("rt::io::sum_to_zero(&mut in__, {n})?"),
                    _ => match elementwise(self, &format!("in__.vec({n})?"))? {
                        Some(c) => c,
                        None => {
                            return Err(unsupported(
                                Default::default(),
                                "this constraint on a vector",
                            ));
                        }
                    },
                }
            }
            TSizedType::Matrix(r, c) => {
                let r = self.size(r)?;
                let c = self.size(c)?;
                match trans {
                    Tr::CholeskyCorr => {
                        format!("rt::io::cholesky_factor_corr(&mut in__, {r}, {lp})?")
                    }
                    Tr::CholeskyCov => {
                        format!("rt::io::cholesky_factor_cov(&mut in__, {r}, {c}, {lp})?")
                    }
                    Tr::Correlation => format!("rt::io::corr_matrix(&mut in__, {r}, {lp})?"),
                    Tr::Covariance => format!("rt::io::cov_matrix(&mut in__, {r}, {lp})?"),
                    Tr::StochasticColumn => {
                        format!("rt::io::stochastic_column(&mut in__, {r}, {c}, {lp})?")
                    }
                    Tr::StochasticRow => {
                        format!("rt::io::stochastic_row(&mut in__, {r}, {c}, {lp})?")
                    }
                    Tr::SumToZero => format!("rt::io::sum_to_zero_matrix(&mut in__, {r}, {c})?"),
                    Tr::Identity => format!("in__.matrix({r}, {c})?"),
                    _ => {
                        let v = self.fresh("v");
                        match elementwise(self, &v)? {
                            Some(body) => format!(
                                "rt::io::on_matrix(in__.matrix({r}, {c})?, |{v}| Ok({body}))?"
                            ),
                            None => {
                                return Err(unsupported(
                                    Default::default(),
                                    "this constraint on a matrix",
                                ));
                            }
                        }
                    }
                }
            }
            TSizedType::Complex => "in__.complex()?".into(),
            _ => {
                return Err(unsupported(
                    Default::default(),
                    "parameters of this type are not supported by stanc-rs yet",
                ));
            }
        })
    }

    /// Emits `let mut name = <constrained value>;` for one parameter.
    fn read_param(&mut self, d: &Decl) -> R<()> {
        let (dims, inner) = parts(&d.ty);
        let uty = d.ty.unsized_type();
        let inner = inner.clone();
        let mut sizes = Vec::new();
        for e in dims {
            let c = self.size(e)?;
            let t = self.fresh("n");
            self.line(&format!("let {t} = {c};"));
            sizes.push(t);
        }
        let mut code = self.read_inner(&inner, &d.trans)?;
        for n in sizes.iter().rev() {
            code = format!("rt::stan::build({n}, || Ok({code}))?");
        }
        self.line(&format!(
            "let mut {}: {} = {code};",
            mangle(&d.name),
            rust_type(&uty, &Ad::AutoDiffable)
        ));
        Ok(())
    }

    /// The number of unconstrained values of a parameter (a `usize` expression).
    fn unconstrained_size(&mut self, d: &Decl) -> R<String> {
        use TTransformation as Tr;
        let (dims, inner) = parts(&d.ty);
        let mut factors = Vec::new();
        for e in dims {
            factors.push(self.size(e)?);
        }
        let inner_size = match inner {
            TSizedType::Real => "1_usize".to_string(),
            TSizedType::Complex => "2_usize".to_string(),
            TSizedType::Vector(n) | TSizedType::RowVector(n) => {
                let n = self.size(n)?;
                match d.trans {
                    Tr::Simplex | Tr::SumToZero => format!("({n}).saturating_sub(1)"),
                    _ => n,
                }
            }
            TSizedType::Matrix(r, c) => {
                let r = self.size(r)?;
                let c = self.size(c)?;
                match d.trans {
                    Tr::CholeskyCorr | Tr::Correlation => {
                        format!("{{ let k = {r}; k * k.saturating_sub(1) / 2 }}")
                    }
                    Tr::Covariance => format!("{{ let k = {r}; k + k * k.saturating_sub(1) / 2 }}"),
                    Tr::CholeskyCov => {
                        format!(
                            "{{ let (m, n) = ({r}, {c}); n * (n + 1) / 2 + m.saturating_sub(n) * n }}"
                        )
                    }
                    Tr::StochasticColumn => format!("({r}).saturating_sub(1) * {c}"),
                    Tr::StochasticRow => format!("{r} * ({c}).saturating_sub(1)"),
                    Tr::SumToZero => format!("({r}).saturating_sub(1) * ({c}).saturating_sub(1)"),
                    _ => format!("{r} * {c}"),
                }
            }
            _ => {
                return Err(unsupported(
                    Default::default(),
                    "parameters of this type are not supported by stanc-rs yet",
                ));
            }
        };
        factors.push(inner_size);
        Ok(format!("({})", factors.join(" * ")))
    }

    /// A `rt::VarInfo` literal for an output variable.
    fn var_info(&mut self, d: &Decl, block: &str) -> R<String> {
        let (dims, inner) = parts(&d.ty);
        let mut ds = Vec::new();
        for e in dims {
            ds.push(self.size(e)?);
        }
        let (complex, matrix) = match inner {
            TSizedType::Int | TSizedType::Real => (false, false),
            TSizedType::Complex => (true, false),
            TSizedType::Vector(n) | TSizedType::RowVector(n) => {
                ds.push(self.size(n)?);
                (false, false)
            }
            TSizedType::ComplexVector(n) | TSizedType::ComplexRowVector(n) => {
                ds.push(self.size(n)?);
                (true, false)
            }
            TSizedType::Matrix(r, c) => {
                ds.push(self.size(r)?);
                ds.push(self.size(c)?);
                (false, true)
            }
            TSizedType::ComplexMatrix(r, c) => {
                ds.push(self.size(r)?);
                ds.push(self.size(c)?);
                (true, true)
            }
            TSizedType::Tuple(_) => {
                return Err(unsupported(
                    Default::default(),
                    "tuple-valued output variables are not supported by stanc-rs yet",
                ));
            }
            TSizedType::Array(..) => unreachable!("array parts"),
        };
        Ok(format!(
            "rt::VarInfo {{ name: {:?}.into(), dims: vec![{}], block: rt::VarBlock::{block}, complex: {complex}, matrix: {matrix} }}",
            d.name,
            ds.join(", ")
        ))
    }

    /// Emits the unconstraining of one parameter read from `values__`.
    fn free_param(&mut self, d: &Decl) -> R<()> {
        use TTransformation as Tr;
        let (dims, inner) = parts(&d.ty);
        let uty = d.ty.unsized_type();
        let read = self.read_json(&d.ty, &d.name, &format!("values__.get({:?})?", d.name))?;
        let v = self.fresh("p");
        self.line(&format!(
            "let {v}: {} = {read};",
            rust_type(&uty, &Ad::DataOnly)
        ));
        let inner = inner.clone();
        let trans = d.trans.clone();
        self.for_leaves(&v, dims.len(), &mut |g, leaf| {
            let code = match (&inner, &trans) {
                (TSizedType::Real, Tr::Identity) => format!("w__.push(*{leaf});"),
                (TSizedType::Real, Tr::Lower(l)) => format!("w__.push(rt::io::free::lb(*{leaf}, {})?);", g.scalar_bound(l)?),
                (TSizedType::Real, Tr::Upper(u)) => format!("w__.push(rt::io::free::ub(*{leaf}, {})?);", g.scalar_bound(u)?),
                (TSizedType::Real, Tr::LowerUpper(l, u)) => {
                    format!("w__.push(rt::io::free::lub(*{leaf}, {}, {})?);", g.scalar_bound(l)?, g.scalar_bound(u)?)
                }
                (TSizedType::Real, Tr::Offset(o)) => {
                    format!("w__.push(rt::io::free::offset_multiplier(*{leaf}, {}, 1.0)?);", g.scalar_bound(o)?)
                }
                (TSizedType::Real, Tr::Multiplier(m)) => {
                    format!("w__.push(rt::io::free::offset_multiplier(*{leaf}, 0.0, {})?);", g.scalar_bound(m)?)
                }
                (TSizedType::Real, Tr::OffsetMultiplier(o, m)) => format!(
                    "w__.push(rt::io::free::offset_multiplier(*{leaf}, {}, {})?);",
                    g.scalar_bound(o)?,
                    g.scalar_bound(m)?
                ),
                (TSizedType::Complex, _) => format!("w__.push({leaf}.re); w__.push({leaf}.im);"),
                (TSizedType::Vector(_) | TSizedType::RowVector(_) | TSizedType::Matrix(..), t) => {
                    let slice = if matches!(inner, TSizedType::Matrix(..)) {
                        format!("{leaf}.as_slice()")
                    } else {
                        format!("&{leaf}[..]")
                    };
                    match t {
                        Tr::Identity => format!("w__.extend_from_slice({slice});"),
                        Tr::Lower(l) => format!("w__.extend(rt::io::free::lb_each({slice}, {})?);", g.io_bound(l)?),
                        Tr::Upper(u) => format!("w__.extend(rt::io::free::ub_each({slice}, {})?);", g.io_bound(u)?),
                        Tr::LowerUpper(l, u) => {
                            format!("w__.extend(rt::io::free::lub_each({slice}, {}, {})?);", g.io_bound(l)?, g.io_bound(u)?)
                        }
                        Tr::Offset(o) => format!(
                            "w__.extend(rt::io::free::offset_multiplier_each({slice}, {}, rt::io::Bound::Scalar(1.0))?);",
                            g.io_bound(o)?
                        ),
                        Tr::Multiplier(m) => format!(
                            "w__.extend(rt::io::free::offset_multiplier_each({slice}, rt::io::Bound::Scalar(0.0), {})?);",
                            g.io_bound(m)?
                        ),
                        Tr::OffsetMultiplier(o, m) => format!(
                            "w__.extend(rt::io::free::offset_multiplier_each({slice}, {}, {})?);",
                            g.io_bound(o)?,
                            g.io_bound(m)?
                        ),
                        Tr::Ordered => format!("w__.extend(rt::io::free::ordered({leaf})?);"),
                        Tr::PositiveOrdered => format!("w__.extend(rt::io::free::positive_ordered({leaf})?);"),
                        Tr::Simplex => format!("w__.extend(rt::io::free::simplex({leaf})?);"),
                        Tr::UnitVector => format!("w__.extend(rt::io::free::unit_vector({leaf})?);"),
                        Tr::SumToZero if matches!(inner, TSizedType::Matrix(..)) => {
                            format!("w__.extend(rt::io::free::sum_to_zero_matrix({leaf})?);")
                        }
                        Tr::SumToZero => format!("w__.extend(rt::io::free::sum_to_zero({leaf})?);"),
                        Tr::CholeskyCorr => format!("w__.extend(rt::io::free::cholesky_factor_corr({leaf})?);"),
                        Tr::CholeskyCov => format!("w__.extend(rt::io::free::cholesky_factor_cov({leaf})?);"),
                        Tr::Correlation => format!("w__.extend(rt::io::free::corr_matrix({leaf})?);"),
                        Tr::Covariance => format!("w__.extend(rt::io::free::cov_matrix({leaf})?);"),
                        Tr::StochasticColumn => format!("w__.extend(rt::io::free::stochastic_column({leaf})?);"),
                        Tr::StochasticRow => format!("w__.extend(rt::io::free::stochastic_row({leaf})?);"),
                        Tr::Tuple(_) => return Err(unsupported(Default::default(), "tuple parameters")),
                    }
                }
                _ => return Err(unsupported(Default::default(), "parameters of this type are not supported by stanc-rs yet")),
            };
            g.line(&code);
            Ok(())
        })
    }
}

