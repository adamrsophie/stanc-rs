#!/usr/bin/env python3
"""Generates `crates/stanc-rs-syntax/src/lr_tables.rs` from stanc3's Menhir automaton.

stanc3 picks each syntax error message by the state of its Menhir parser. This script turns
Menhir's description of that automaton and the compiled `parser.messages` into Rust tables, so
that stanc-rs can replay the tokens of a rejected program and print stanc3's message.

Usage, with Menhir 20260209 (the version stanc3 v2.40.0 pins) on the PATH:

    cp STANC3_DIR/src/frontend/parser.{mly,messages} WORK_DIR && cd WORK_DIR
    menhir --strict --unused-tokens --dump-resolved parser.mly
    menhir --strict --unused-tokens parser.mly --compile-errors parser.messages > errors.ml
    python3 tools/menhir_tables.py WORK_DIR > crates/stanc-rs-syntax/src/lr_tables.rs

The flags are those of stanc3's build (`src/frontend/dune`), so state numbers agree.
"""
import os
import re
import sys

work = sys.argv[1]
auto = open(os.path.join(work, "parser.automaton.resolved")).read()
mly = open(os.path.join(work, "parser.mly")).read()
errors = open(os.path.join(work, "errors.ml")).read()

# Terminals, in declaration order.
terminals = []
for d in re.findall(r"^%token\b(.*?)(?=^%|^\(\*|\Z)", mly, re.M | re.S):
    d = re.sub(r"\"(?:[^\"\\]|\\.)*\"|<[^>]*>", "", d)
    for name in re.findall(r"\b[A-Z_][A-Z_0-9]*\b", d):
        if name not in terminals:
            terminals.append(name)
term_index = {t: i for i, t in enumerate(terminals)}

states = {}
prods = {}
nonterms = {}


def prod(text):
    text = text.strip()
    if text not in prods:
        lhs, rhs = text.split("->")
        lhs = lhs.strip()
        prods[text] = (len(prods), lhs, len(rhs.split()))
    return prods[text][0]


def nonterm(n):
    return nonterms.setdefault(n, len(nonterms))


starts = {}
for block in re.split(r"\n(?=State \d+:\n)", auto):
    m = re.match(r"State (\d+):\n", block)
    if not m:
        continue
    s = int(m.group(1))
    acts, gotos, default = {}, {}, None
    lines = block.split("\n")
    for i, line in enumerate(lines):
        if re.match(r"(functions_only|program)' -> \. ", line):
            starts[line.split("'")[0]] = s
        m = re.match(r"-- On (\S+) shift to state (\d+)$", line)
        if m:
            sym, t = m.group(1), int(m.group(2))
            if sym in term_index:
                acts[term_index[sym]] = t
            else:
                gotos[nonterm(sym)] = t
            continue
        m = re.match(r"-- On ((?:\S+ ?)+)$", line)
        if m and i + 1 < len(lines):
            r = re.match(r"--   reduce production (.*)$", lines[i + 1])
            if r:
                p = prod(r.group(1))
                for sym in m.group(1).split():
                    acts[term_index[sym]] = -p - 1
            continue
        m = re.match(r"-- (?:After|Without) reading the next token, reduce production (.*)$", line)
        if m:
            default = prod(m.group(1))
            continue
        m = re.match(r"-- Without reading the next token, accept (\S+)$", line)
        if m:
            default = prod(f"{m.group(1)}' -> {m.group(1)}")
    states[s] = (acts, gotos, default)

n = max(states) + 1
assert sorted(states) == list(range(n))

# Messages by state.
msgs, msg_of_state = [], [None] * n
for nums, text in re.findall(r"\| ((?:\d+ \| )*\d+) ->\n\s+(\"(?:[^\"\\]|\\.)*\")", errors):
    msgs.append(text)
    for x in nums.split(" | "):
        msg_of_state[int(x)] = len(msgs) - 1

out = ["// Generated by tools/menhir_tables.py from stanc3 v2.40.0's parser.mly and parser.messages",
       "// with Menhir 20260209. Do not edit.", ""]
out.append(f"pub static TERMINALS: [&str; {len(terminals)}] = [" +
           ", ".join(f'"{t}"' for t in terminals) + "];")
out.append(f"pub static START_PROGRAM: u16 = {starts['program']};")
out.append(f"pub static START_FUNCTIONS_ONLY: u16 = {starts['functions_only']};")
plist = sorted(prods.values())
out.append(f"pub static PROD_LHS: [u16; {len(plist)}] = [" + ", ".join(
    "u16::MAX" if lhs.endswith("'") else str(nonterm(lhs)) for _, lhs, _ in plist) + "];")
out.append(f"pub static PROD_LEN: [u8; {len(plist)}] = [" +
           ", ".join(str(k) for _, _, k in plist) + "];")
starts_a, acts_a, starts_g, gotos_a, defaults = [0], [], [0], [], []
for s in range(n):
    acts, gotos, default = states[s]
    acts_a += sorted(acts.items())
    starts_a.append(len(acts_a))
    gotos_a += sorted(gotos.items())
    starts_g.append(len(gotos_a))
    defaults.append(-1 if default is None else default)
out.append(f"pub static ACTION_START: [u16; {n + 1}] = [" + ", ".join(map(str, starts_a)) + "];")
out.append(f"pub static ACTIONS: [(u8, i32); {len(acts_a)}] = [" +
           ", ".join(f"({t}, {a})" for t, a in acts_a) + "];")
out.append(f"pub static GOTO_START: [u16; {n + 1}] = [" + ", ".join(map(str, starts_g)) + "];")
out.append(f"pub static GOTOS: [(u16, u16); {len(gotos_a)}] = [" +
           ", ".join(f"({g}, {t})" for g, t in gotos_a) + "];")
out.append(f"pub static DEFAULT_REDUCTION: [i32; {n}] = [" + ", ".join(map(str, defaults)) + "];")
out.append(f"pub static MESSAGE_OF_STATE: [u16; {n}] = [" + ", ".join(
    "u16::MAX" if m is None else str(m) for m in msg_of_state) + "];")
out.append(f"pub static MESSAGES: [&str; {len(msgs)}] = [")
out += [f"    {m}," for m in msgs]
out.append("];")
print("\n".join(out))
